#!/usr/bin/env bash
# Generates the probe package: N distinct struct element types, each used the
# way an application repository uses a Stream — a slice-backed source, a Map
# to an Entry, a Filter, a Collect and a FindFirst. Nothing concurrent.
# Usage: gen.sh <N>
set -euo pipefail
n=${1:?N}
out=probe
mkdir -p "$out"
{
  echo '// Code generated by gen.sh; DO NOT EDIT.'
  echo
  echo 'package probe'
  echo
  echo 'import ('
  echo '	"context"'
  echo '	"errors"'
  echo
  echo '	"github.com/shpandrak/shpanstream"'
  echo '	"github.com/shpandrak/shpanstream/stream"'
  echo ')'
  for ((i = 0; i < n; i++)); do
    cat <<GO

// T$i is one element type; its field set differs from every other T so the
// compiler cannot share a GC shape between them.
type T$i struct {
	Id    string
	Rank  int
	Tags  []string
	Extra [$((i + 1))]byte
}

func list$i(ctx context.Context) stream.Stream[T$i] {
	return stream.FromSlice([]T$i{{Id: "a", Rank: $i}, {Id: "b", Rank: $((i + 1))}})
}

func entries$i(ctx context.Context) stream.Stream[shpanstream.Entry[string, T$i]] {
	return stream.Map(list$i(ctx), func(t T$i) shpanstream.Entry[string, T$i] {
		return shpanstream.Entry[string, T$i]{Key: t.Id, Value: t}
	})
}

// Use$i exercises the five operations every repository type pays for.
func Use$i(ctx context.Context) (int, error) {
	all, err := entries$i(ctx).Filter(func(e shpanstream.Entry[string, T$i]) bool { return e.Value.Rank > 0 }).Collect(ctx)
	if err != nil {
		return 0, err
	}
	first, found, err := list$i(ctx).FindFirst(ctx)
	if err != nil {
		return 0, err
	}
	if !found {
		return 0, errors.New("empty")
	}
	return len(all) + first.Rank, nil
}
GO
  done
} > "$out/probe_gen.go"
gofmt -w "$out/probe_gen.go"
